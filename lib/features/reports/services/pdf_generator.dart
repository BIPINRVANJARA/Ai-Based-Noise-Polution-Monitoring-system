import 'dart:typed_data';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

class PdfGenerator {
  Future<Uint8List> generateIncidentReport(List<dynamic> data, {DateTime? from, DateTime? to}) async {
    final pdf = pw.Document();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        header: (context) => _buildHeader(),
        footer: (context) => _buildFooter(context),
        build: (context) => [
          _buildSummary(),
          pw.SizedBox(height: 20),
          _buildViolationsTable(),
          pw.SizedBox(height: 20),
          _buildThresholdReference(),
        ],
      ),
    );

    final bytes = await pdf.save();
    
    // Attempt to share/preview using printing
    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => bytes,
    );

    return bytes;
  }

  pw.Widget _buildHeader() {
    return pw.Container(
      margin: const pw.EdgeInsets.only(bottom: 20),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text('NoiseGuard', style: pw.TextStyle(fontSize: 24, fontWeight: pw.FontWeight.bold, color: PdfColors.green800)),
          pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.end,
            children: [
              pw.Text('Incident Report', style: pw.TextStyle(fontSize: 18)),
              pw.Text('Date: ${DateTime.now().toString().split(' ')[0]}', style: const pw.TextStyle(fontSize: 12, color: PdfColors.grey700)),
            ],
          )
        ],
      ),
    );
  }

  pw.Widget _buildSummary() {
    return pw.Container(
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(border: pw.Border.all(color: PdfColors.grey)),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceAround,
        children: [
          _summaryItem('Avg dB', '65.2'),
          _summaryItem('Max dB', '102.4'),
          _summaryItem('Total Readings', '4,521'),
          _summaryItem('Violations', '14'),
        ],
      ),
    );
  }

  pw.Widget _summaryItem(String title, String value) {
    return pw.Column(
      children: [
        pw.Text(title, style: const pw.TextStyle(fontSize: 12, color: PdfColors.grey700)),
        pw.Text(value, style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold)),
      ],
    );
  }

  pw.Widget _buildViolationsTable() {
    return pw.TableHelper.fromTextArray(
      headers: ['Date', 'Time', 'Location', 'dB Level', 'Source'],
      data: [
        ['2026-07-28', '14:30', 'Downtown', '95', 'Construction'],
        ['2026-07-28', '16:45', 'Main St', '88', 'Traffic'],
      ],
      headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold),
      headerDecoration: const pw.BoxDecoration(color: PdfColors.grey300),
      cellHeight: 30,
      cellAlignments: {
        0: pw.Alignment.centerLeft,
        1: pw.Alignment.centerLeft,
        2: pw.Alignment.centerLeft,
        3: pw.Alignment.center,
        4: pw.Alignment.centerLeft,
      },
    );
  }

  pw.Widget _buildThresholdReference() {
    return pw.Container(
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text('Noise Threshold Reference', style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold)),
          pw.SizedBox(height: 5),
          pw.Text('Hospital/Quiet Zone: < 50 dB'),
          pw.Text('Residential: < 60 dB'),
          pw.Text('Commercial: < 70 dB'),
          pw.Text('Industrial: < 85 dB'),
        ],
      ),
    );
  }

  pw.Widget _buildFooter(pw.Context context) {
    return pw.Container(
      margin: const pw.EdgeInsets.only(top: 20),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text('Generated by NoiseGuard v3.0', style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey)),
          pw.Text('Page ${context.pageNumber} of ${context.pagesCount}', style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey)),
        ],
      ),
    );
  }
}
